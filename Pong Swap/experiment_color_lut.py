"""Isolated exact uint8 RGB-to-LAB lookup experiment.

The 256^3-entry table is generated by the original Torch implementation, not
reimplemented color math. Inverse LAB-to-RGB and channel statistics stay original.
Prewarm must run on the CUDA-owner thread outside a timed render; no GPU work
occurs at import or install. Full-frame CRC still gates any adoption.
"""

import ctypes as ct
import inspect
import threading
import time

from experiment_cuda_module import CudaModule


COLORS = 1 << 24
CHUNK = 1 << 20
SOURCE = r'''
extern "C" __global__ void rgb_lab_lut(
    const unsigned char* rgb, const float* table, float* lab, int n
) {
    int p = blockIdx.x * blockDim.x + threadIdx.x;
    if (p >= n) return;
    unsigned int key = ((unsigned int)rgb[p] << 16) |
                       ((unsigned int)rgb[n+p] << 8) |
                       (unsigned int)rgb[2*n+p];
    const int colors = 16777216;
    lab[p] = table[key];
    lab[n+p] = table[colors+key];
    lab[2*n+p] = table[2*colors+key];
}
extern "C" __global__ void rgb_lab_lut_strided(
    const unsigned char* rgb, const float* table, float* lab,
    int height, int width, long long channel_stride,
    long long row_stride, long long column_stride
) {
    int p = blockIdx.x * blockDim.x + threadIdx.x;
    int n = height * width;
    if (p >= n) return;
    long long base = (long long)(p / width) * row_stride
                   + (long long)(p % width) * column_stride;
    unsigned int key = ((unsigned int)rgb[base] << 16) |
                       ((unsigned int)rgb[base+channel_stride] << 8) |
                       (unsigned int)rgb[base+2*channel_stride];
    const int colors = 16777216;
    lab[p] = table[key];
    lab[n+p] = table[colors+key];
    lab[2*n+p] = table[2*colors+key];
}
'''

_original = None
_module = None
_table = None
_build_seconds = None
_lock = threading.RLock()
_coverage = {"lookup": 0, "lookupStrided": 0, "fallback": 0}


def coverage():
    return {**_coverage, "buildSeconds": _build_seconds,
            "tableBytes": 3 * COLORS * 4 if _table is not None else 0}


def _prewarm_unlocked():
    """Build complete LUT with original Torch math and finish before returning."""
    global _module, _table, _build_seconds
    import torch

    if _table is not None:
        return
    if _original is None:
        raise RuntimeError("Call install() before prewarm()")
    if torch.cuda.current_device() != 0:
        raise RuntimeError("Color LUT experiment requires CUDA:0")
    start_time = time.perf_counter()
    table = torch.empty((3, COLORS), dtype=torch.float32, device="cuda:0")
    for first in range(0, COLORS, CHUNK):
        last = first + CHUNK
        keys = torch.arange(first, last, device="cuda:0", dtype=torch.int32)
        rgb = torch.stack(((keys >> 16).to(torch.uint8),
                           (keys >> 8).to(torch.uint8),
                           keys.to(torch.uint8)), dim=0).reshape(3, 1024, 1024)
        lab = _original(rgb)
        for channel in range(3):
            table[channel, first:last].copy_(lab[channel].reshape(-1))
    module = CudaModule(SOURCE, ["rgb_lab_lut", "rgb_lab_lut_strided"])
    torch.cuda.current_stream(0).synchronize()
    _table, _module = table, module
    _build_seconds = time.perf_counter() - start_time


def prewarm():
    """Serialize one-time table creation across concurrent sessions."""
    with _lock:
        _prewarm_unlocked()


def release():
    """Release after all users and any graphs capturing lookups are destroyed."""
    global _table, _module
    import torch

    with _lock:
        if _table is not None:
            torch.cuda.synchronize(0)
        if _module is not None:
            unload = _module.driver.cuModuleUnload
            unload.argtypes = [ct.c_void_p]
            unload.restype = ct.c_int
            _module.check(unload(_module.module))
        _table = None
        _module = None


def _launch_lookup(rgb):
    import torch

    with _lock:
        _prewarm_unlocked()
        out = torch.empty(rgb.shape, device=rgb.device, dtype=torch.float32)
        n = rgb.shape[1] * rgb.shape[2]
        if rgb.is_contiguous():
            _module.launch("rgb_lab_lut", n,
                           [ct.c_void_p(rgb.data_ptr()), ct.c_void_p(_table.data_ptr()),
                            ct.c_void_p(out.data_ptr()), ct.c_int(n)],
                           [rgb, _table, out])
            _coverage["lookup"] += 1
        else:
            stride = rgb.stride()
            _module.launch("rgb_lab_lut_strided", n,
                           [ct.c_void_p(rgb.data_ptr()), ct.c_void_p(_table.data_ptr()),
                            ct.c_void_p(out.data_ptr()), ct.c_int(rgb.shape[1]),
                            ct.c_int(rgb.shape[2]), ct.c_longlong(stride[0]),
                            ct.c_longlong(stride[1]), ct.c_longlong(stride[2])],
                           [rgb, _table, out])
            _coverage["lookupStrided"] += 1
        return out


def install():
    """Process-local forward-only patch. Must precede prewarm on same process."""
    global _original
    from rope import VideoManager as vm
    import torch

    if _original is not None:
        return
    source = inspect.getsource(vm._rgb_chw_to_lab)
    if ("rgb.to(torch.float32).clamp_(0, 255) / 255.0" not in source
            or "return torch.stack([L, a, b], dim=0)" not in source):
        raise RuntimeError("RGB-to-LAB source contract changed")
    _original = vm._rgb_chw_to_lab

    def lookup(rgb):
        if (rgb.is_cuda and rgb.device.index == 0 and rgb.dtype == torch.uint8
                and rgb.ndim == 3 and rgb.shape[0] == 3
                and rgb.shape[1] > 0 and rgb.shape[2] > 0
                and all(stride > 0 for stride in rgb.stride())):
            return _launch_lookup(rgb)
        _coverage["fallback"] += 1
        return _original(rgb)

    vm._rgb_chw_to_lab = lookup
